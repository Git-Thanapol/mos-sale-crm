"""Parity fixture harness — the keystone of the CRM V2 port.

Every `*_parity` test in tests/unit replays case tables exported from the
CRM V2 prototype (checkpoint f97f955874f6bea0b43cd7723039b6ca50fe398c) so
that "ported correctly" is evidence rather than an assertion. The fixtures
are generated by scripts/export_crmv2_fixtures.ts and are never hand-edited
— see tests/fixtures/crmv2/README.md.
"""

import json
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

FIXTURE_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "crmv2"


def load_cases(module: str) -> list[dict]:
    cases = json.loads((FIXTURE_DIR / f"{module}.json").read_text(encoding="utf-8"))
    assert cases, f"{module}.json is empty"
    for case in cases:
        assert set(case) >= {"name", "input", "expected"}
    return cases


def test_every_fixture_file_is_loadable():
    files = sorted(p.stem for p in FIXTURE_DIR.glob("*.json"))
    assert files == ["last_order_age", "missed_channel", "ownership"]
    for module in files:
        load_cases(module)
